defmodule Backplane.Tools.Admin do
  @moduledoc """
  Native MCP tools for client management.

  These tools are scoped to `admin::*` — only clients with `"admin::*"` or `"*"`
  scope can call them (enforced by the scope guard in McpHandler).
  """

  @behaviour Backplane.Tools.ToolModule

  alias Backplane.Clients

  @impl true
  def tools do
    [
      %{
        name: "admin::list-clients",
        description: "List all registered MCP clients with their scopes and status",
        input_schema: %{
          "type" => "object",
          "properties" => %{}
        },
        module: __MODULE__,
        handler: :list_clients
      },
      %{
        name: "admin::upsert-client",
        description:
          "Create or update an MCP client. The server issues a token on create; set rotate_token to true to rotate an existing token. Issued tokens are returned once. Requires a synchronous call without Idempotency-Key.",
        input_schema: %{
          "type" => "object",
          "properties" => %{
            "name" => %{
              "type" => "string",
              "description" => "Client identifier (unique)"
            },
            "rotate_token" => %{
              "type" => "boolean",
              "description" => "Issue a replacement token for an existing client (default false)"
            },
            "scopes" => %{
              "type" => "array",
              "items" => %{"type" => "string"},
              "description" =>
                "Tool scope allowlist. Examples: [\"*\"], [\"skill::*\"], [\"math::evaluate\"], [\"admin::*\"]"
            },
            "active" => %{
              "type" => "boolean",
              "description" => "Whether the client is active (default true)"
            }
          },
          "required" => ["name", "scopes"],
          "additionalProperties" => false
        },
        module: __MODULE__,
        handler: :upsert_client
      }
    ]
  end

  @impl true
  def call(%{"_handler" => "list_clients"}) do
    clients =
      Clients.list_clients()
      |> Enum.map(fn client ->
        %{
          id: client.id,
          name: client.name,
          scopes: client.scopes,
          active: client.active,
          last_seen_at: client.last_seen_at && DateTime.to_iso8601(client.last_seen_at)
        }
      end)

    {:ok, %{clients: clients}}
  end

  def call(%{"_handler" => "upsert_client"} = args) do
    cond do
      Enum.any?(
        ["token", "token_hash", "token_digest", "scheme", "credential_scheme"],
        &Map.has_key?(args, &1)
      ) ->
        {:error,
         "Credentials are generated by the server; custom credential fields are not accepted"}

      Map.has_key?(args, "rotate_token") and not is_boolean(args["rotate_token"]) ->
        {:error, "rotate_token must be a boolean"}

      not is_binary(args["name"]) or args["name"] == "" ->
        {:error, "name is required"}

      true ->
        upsert_client(args)
    end
  end

  defp upsert_client(args) do
    attrs = Map.take(args, ["name", "scopes", "active"])

    result =
      case Clients.get_client_by_name(args["name"]) do
        nil ->
          Clients.issue_client(attrs)

        existing ->
          if args["rotate_token"] == true,
            do: Clients.rotate_client_token(existing, attrs),
            else: Clients.update_client(existing, attrs)
      end

    case result do
      {:ok, client, token} -> {:ok, Map.put(format_client(client), :token, token)}
      {:ok, client} -> {:ok, format_client(client)}
      {:error, changeset} -> {:error, format_errors(changeset)}
    end
  end

  defp format_client(client) do
    %{
      id: client.id,
      name: client.name,
      scopes: client.scopes,
      active: client.active
    }
  end

  defp format_errors(changeset) do
    Ecto.Changeset.traverse_errors(changeset, fn {msg, opts} ->
      Enum.reduce(opts, msg, fn {key, value}, acc ->
        String.replace(acc, "%{#{key}}", to_string(value))
      end)
    end)
    |> Enum.map_join("; ", fn {field, errors} -> "#{field}: #{Enum.join(errors, ", ")}" end)
  end
end
