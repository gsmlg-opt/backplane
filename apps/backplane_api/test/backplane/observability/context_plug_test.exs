defmodule Backplane.Observability.ContextPlugTest do
  use ExUnit.Case, async: true

  alias Backplane.Observability.{Context, ContextPlug}

  test "reuses the request ID generated by Plug.RequestId" do
    conn =
      Plug.Test.conn(:get, "/v1/models")
      |> Plug.RequestId.call(Plug.RequestId.init([]))

    [request_id] = Plug.Conn.get_resp_header(conn, "x-request-id")
    refute Map.has_key?(conn.assigns, :request_id)

    conn = ContextPlug.call(conn, [])

    assert Context.get(conn).request_id == request_id
    assert Logger.metadata()[:request_id] == request_id
    assert Plug.Conn.get_resp_header(conn, "x-request-id") == [request_id]
  end

  test "reuses the inbound request ID accepted by Plug.RequestId" do
    request_id = "accepted-request-id-12345"

    conn =
      Plug.Test.conn(:get, "/v1/models")
      |> Plug.Conn.put_req_header("x-request-id", request_id)
      |> Plug.RequestId.call(Plug.RequestId.init([]))
      |> ContextPlug.call([])

    assert Context.get(conn).request_id == request_id
    assert Logger.metadata()[:request_id] == request_id
    assert Plug.Conn.get_resp_header(conn, "x-request-id") == [request_id]
  end

  test "does not restore inbound request IDs rejected by Plug.RequestId" do
    for rejected_id <- ["", "short-id", String.duplicate("x", 201)] do
      conn =
        Plug.Test.conn(:get, "/v1/models")
        |> Plug.Conn.put_req_header("x-request-id", rejected_id)
        |> Plug.RequestId.call(Plug.RequestId.init([]))

      [request_id] = Plug.Conn.get_resp_header(conn, "x-request-id")
      refute request_id == rejected_id

      conn = ContextPlug.call(conn, [])

      assert Context.get(conn).request_id == request_id
      assert Logger.metadata()[:request_id] == request_id
    end
  end

  test "prefers the response request ID over an existing assign" do
    conn =
      Plug.Test.conn(:get, "/v1/models")
      |> Plug.Conn.assign(:request_id, "stale-assigned-id")
      |> Plug.RequestId.call(Plug.RequestId.init([]))

    [request_id] = Plug.Conn.get_resp_header(conn, "x-request-id")
    conn = ContextPlug.call(conn, [])

    assert Context.get(conn).request_id == request_id
    assert Logger.metadata()[:request_id] == request_id
  end

  test "assigns request and generated trace context" do
    conn =
      Plug.Test.conn(:get, "/v1/models")
      |> Plug.Conn.put_req_header("x-request-id", "req-header-1")
      |> ContextPlug.call([])

    assert %Context{request_id: "req-header-1", trace_id: trace_id, span_id: span_id} =
             Context.get(conn)

    assert byte_size(trace_id) == 32
    assert byte_size(span_id) == 16
  end

  test "reuses inbound traceparent context" do
    trace_id = String.duplicate("c", 32)
    parent_id = String.duplicate("d", 16)

    conn =
      Plug.Test.conn(:get, "/mcp")
      |> Plug.Conn.put_req_header("traceparent", "00-#{trace_id}-#{parent_id}-01")
      |> ContextPlug.call([])

    assert %Context{trace_id: ^trace_id, parent_span_id: ^parent_id} = Context.get(conn)
  end
end
